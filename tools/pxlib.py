class Canvas:
    """An RGBA pixel buffer. All coordinates are integers; nothing is smoothed."""

    def __init__(self, w, h, bg=None):
        self.w = w
        self.h = h
        self.img = Image.new('RGBA', (w, h), c(bg) if bg else TRANSPARENT)
        self.p = self.img.load()

    # -- primitives --------------------------------------------------------

    def px(self, x, y, col):
        x, y = int(x), int(y)
        if 0 <= x < self.w and 0 <= y < self.h and col is not None:
            if len(col) == 4 and col[3] == 0:
                return
            if len(col) == 4 and col[3] < 255:
                # manual alpha blend — Image.paste would resample
                sr, sg, sb, sa = col
                dr, dg, db, da = self.p[x, y]
                a = sa / 255.0
                self.p[x, y] = (
                    int(sr * a + dr * (1 - a)),
                    int(sg * a + dg * (1 - a)),
                    int(sb * a + db * (1 - a)),
                    max(da, sa),
                )
            else:
                self.p[x, y] = col

    def rect(self, x, y, w, h, col):
        for j in range(int(h)):
            for i in range(int(w)):
                self.px(x + i, y + j, col)

    def frame(self, x, y, w, h, col):
        """1px outline, drawn inside the given box."""
        self.hline(x, y, w, col)
        self.hline(x, y + h - 1, w, col)
        self.vline(x, y, h, col)
        self.vline(x + w - 1, y, h, col)

    def hline(self, x, y, w, col):
        for i in range(int(w)):
            self.px(x + i, y, col)

    def vline(self, x, y, h, col):
        for j in range(int(h)):
            self.px(x, y + j, col)

    def line(self, x0, y0, x1, y1, col):
        """Bresenham — no diagonal anti-aliasing, which is the whole point."""
        x0, y0, x1, y1 = int(x0), int(y0), int(x1), int(y1)
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            self.px(x0, y0, col)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def circle(self, cx, cy, r, col, fill=True):
        for j in range(-r, r + 1):
            for i in range(-r, r + 1):
                d = i * i + j * j
                if (d <= r * r) if fill else (r * r - r <= d <= r * r + r):
                    self.px(cx + i, cy + j, col)

    # -- texture -----------------------------------------------------------

    def dither(self, x, y, w, h, col, density=2, offset=0):
        """
        Ordered dithering. density 2 = checkerboard (50%), 3 = ~33%, 4 = 25%.
        This is how you get a gradient without adding colours to the palette.
        """
        for j in range(int(h)):
            for i in range(int(w)):
                if (i + j * (density - 1) + offset) % density == 0:
                    self.px(x + i, y + j, col)

    def scatter(self, x, y, w, h, col, chance, rng):
        for j in range(int(h)):
            for i in range(int(w)):
                if rng.random() < chance:
                    self.px(x + i, y + j, col)

    def grain(self, x, y, w, h, col, rng, chance=0.06):
        """Sparse speckle — wood grain, wall texture, paper tooth."""
        self.scatter(x, y, w, h, col, chance, rng)

    # -- shading helpers ---------------------------------------------------

    def bevel(self, x, y, w, h, light, dark):
        """Classic 1px raised edge: light on top/left, dark on bottom/right."""
        self.hline(x, y, w - 1, light)
        self.vline(x, y, h - 1, light)
        self.hline(x + 1, y + h - 1, w - 1, dark)
        self.vline(x + w - 1, y + 1, h - 1, dark)

    def glow(self, cx, cy, r, col, steps=4):
        """Soft radial light, dithered outward so it stays in-palette."""
        for s in range(steps, 0, -1):
            rr = int(r * s / steps)
            density = 1 + (steps - s + 1)
            for j in range(-rr, rr + 1):
                for i in range(-rr, rr + 1):
                    if i * i + j * j <= rr * rr:
                        if (i + j * (density - 1)) % density == 0:
                            self.px(cx + i, cy + j, col)

    # -- output ------------------------------------------------------------

    def paste(self, other, x, y):
        self.img.alpha_composite(other.img, (int(x), int(y)))

    def save(self, path):
        self.img.save(path)
        return path


