def wood_panel(cv, x, y, w, h, rng, base='wood', dark='wood_d', light='wood_l',
               edge='wood_dd', grain_chance=0.05):
    """A plank with grain, a lit top edge and a shadowed bottom edge."""
    cv.rect(x, y, w, h, c(base))
    cv.hline(x, y, w, c(light))
    cv.hline(x, y + h - 1, w, c(edge))
    cv.grain(x, y + 1, w, h - 2, c(dark), rng, grain_chance)
    # a few long grain streaks
    for _ in range(max(1, w // 40)):
        gy = y + rng.randint(1, max(1, h - 2))
        gx = x + rng.randint(0, max(1, w - 12))
        cv.hline(gx, gy, rng.randint(6, max(7, min(28, w - (gx - x)))), c(dark))


BOOK_COLORS = [
    ('red_d', 'red', 'orange'),
    ('blue_d', 'blue', 'teal_ll'),
    ('purple', 'plum', 'amber_l'),
    ('teal_d', 'teal', 'teal_ll'),
    ('wood_dd', 'wood_d', 'wood_l'),
    ('grn_dd', 'grn_d', 'grn_l'),
    ('red_d', 'plum', 'gold'),
    ('blue_d', 'teal_d', 'teal_l'),
    ('ink2', 'shadow', 'cream_d'),
    ('amber_d', 'orange', 'amber_l'),
]

# Brown reads as shelf woodwork; near-black reads as an empty slot. Inside a
# keep-clear band each is swapped for a spine that reads as a book.
_MASQUERADE = {
    ('wood_dd', 'wood_d', 'wood_l'):  ('red_d', 'plum', 'gold'),
    ('ink2', 'shadow', 'cream_d'):    ('blue_d', 'blue', 'teal_ll'),
}


def book_spine(cv, x, y, w, h, rng, scheme=None, gilt=True):
    """
    One book seen spine-on in a shelf. Variation is doing the heavy lifting
    here — matching books read as a texture, varied ones read as a library.
    """
    dark, base, light = scheme or rng.choice(BOOK_COLORS)

    cv.rect(x, y, w, h, c(base))
    cv.vline(x, y, h, c(light))            # lit left edge
    cv.vline(x + w - 1, y, h, c(dark))     # shadowed right edge
    cv.hline(x, y, w, c(dark))             # top of the spine
    cv.hline(x, y + h - 1, w, c(dark))     # base

    # rounded head and tail, like a hardback
    cv.px(x, y, TRANSPARENT)
    cv.px(x + w - 1, y, TRANSPARENT)
    cv.px(x, y, c(dark))
    cv.px(x + w - 1, y, c(dark))

    if w >= 4 and gilt:
        gold_c = c('gold') if rng.random() < 0.7 else c('cream_d')
        # bands near head and tail
        by1 = y + rng.randint(3, 6)
        by2 = y + h - rng.randint(4, 8)
        cv.hline(x + 1, by1, w - 2, gold_c)
        if by2 > by1 + 6:
            cv.hline(x + 1, by2, w - 2, gold_c)
        # title marks between the bands
        if w >= 5 and by2 - by1 > 14:
            ty = by1 + 4
            while ty < by2 - 3:
                if rng.random() < 0.75:
                    cv.hline(x + 2, ty, max(1, w - 4), gold_c)
                ty += rng.randint(3, 5)

    # a little wear on the top edge
    if rng.random() < 0.35:
        cv.px(x + rng.randint(1, max(1, w - 2)), y + 1, c('ink'))


def fill_shelf_row(cv, x0, x1, base_y, max_h, rng, skips=None,
                   keep_clear=None):
    """
    Pack a shelf with books of varied width, height and colour, leaving each
    entry of `skips` (a list of (x, w) tuples) empty for the books that matter. Returns nothing; draws in
    place. Occasionally lays a book flat or leans one against its neighbour.
    """
    skips = skips or []
    keep_clear = keep_clear or []

    def scheme_for(sx, sw):
        """
        Pick a spine colourway. Always draws from the rng so the shelf never
        reshuffles, then remaps inside a keep-clear band: the brown scheme
        reads as shelf woodwork and the near-black one reads as a hole, and
        either one next to a hero book makes it look wedged against the frame.
        """
        s = rng.choice(BOOK_COLORS)
        if s in _MASQUERADE and any(sx + sw > z[0] and sx < z[0] + z[1]
                                    for z in keep_clear):
            return _MASQUERADE[s]
        return s

    def snap(sx, span):
        """
        Trim a width or a step so it stands flush against the next hero slot.
        The slots are the only place on the shelf where the dark backing can
        show through, and a one-pixel sliver of it beside a book reads as a
        black rule boxing the book in — which is worse than a book being a
        pixel narrower than it wanted to be.
        """
        for s in skips:
            if sx < s[0] <= sx + span + 2:
                return s[0] - sx
        return span

    x = x0
    while x < x1 - 2:
        hit = [s for s in skips if s[0] <= x < s[0] + s[1]]
        if hit:
            x = hit[0][0] + hit[0][1]   # the next book butts up against it
            continue

        w = rng.randint(3, 8)
        if x + w > x1:
            w = x1 - x
        if w < 2:
            break
        w = snap(x, w)

        h = rng.randint(int(max_h * 0.62), max_h)
        y = base_y - h

        # a stack lying flat, every so often
        clash = any(x + 22 > s[0] and x < s[0] + s[1] for s in skips)
        if rng.random() < 0.07 and x + 22 < x1 and not clash:
            stack_w = rng.randint(16, 22)
            sy = base_y
            for _ in range(rng.randint(2, 3)):
                dark, base, light = scheme_for(x, stack_w)
                bh = rng.randint(4, 6)
                sy -= bh
                cv.rect(x, sy, stack_w, bh, c(base))
                cv.hline(x, sy, stack_w, c(light))
                cv.hline(x, sy + bh - 1, stack_w, c(dark))
                cv.vline(x + stack_w - 1, sy, bh, c(dark))
                # page edges on the right
                cv.vline(x + stack_w - 2, sy + 1, bh - 2, c('cream_m'))
                stack_w -= rng.randint(0, 2)
            x += rng.randint(18, 24)
            continue

        book_spine(cv, x, y, w, h, rng, scheme=scheme_for(x, w))
        x += snap(x, w + (1 if rng.random() < 0.25 else 0))


def leaf(cv, x, y, col_d, col, rng, size=3):
    """A single small leaf — used to build vines and plants."""
    cv.px(x, y, col_d)
    for i in range(1, size):
        cv.px(x + i, y, col)
        cv.px(x + i, y - 1 if rng.random() < 0.5 else y + 1, col_d)


def vine(cv, x, y, length, rng, col_d='grn_dd', col='grn_d', col_l='grn'):
    """A hanging vine with leaves, drawn top-down with a slight wander."""
    cx = x
    for j in range(length):
        cv.px(cx, y + j, c(col_d))
        if j % 4 == 0 and j > 2:
            side = 1 if (j // 4) % 2 == 0 else -1
            for k in range(1, rng.randint(2, 4)):
                cv.px(cx + side * k, y + j - (k // 2), c(col))
                cv.px(cx + side * k, y + j + 1 - (k // 2), c(col_l))
        if j % 7 == 6:
            cx += rng.choice((-1, 0, 1))


def dust_shaft(cv, x, y, w, h, rng, col='amber_l', alpha=26):
    """A soft diagonal light shaft — dithered so it stays chunky."""
    for j in range(h):
        row_w = int(w * (0.4 + 0.6 * j / h))
        for i in range(row_w):
            if (i + j) % 3 == 0 and rng.random() < 0.5:
                cv.px(x + i + j // 3, y + j, c(col, alpha))
