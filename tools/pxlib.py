"""
pxlib — a tiny pixel-art drawing library.

Every asset in this portfolio is drawn pixel by pixel from code, not painted in
an image editor and not generated by a model. This module is the brush set:
integer coordinates only, a fixed palette, no anti-aliasing anywhere.

Run `python tools/build_assets.py` to regenerate everything in assets/px/.
"""

